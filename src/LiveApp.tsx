import { useState } from 'react';
import type { LiveMarket } from './app/useLiveMarket';
import { randomSeed } from './app/seed';
import { formatCents } from './engine';
import { Header, type Mode } from './ui/Header';
import { LiveAccountPanel } from './ui/LiveAccountPanel';
import { LiveChart } from './ui/LiveChart';
import { LiveHoldings } from './ui/LiveHoldings';
import { LiveStockList } from './ui/LiveStockList';
import { LiveTradeHistory } from './ui/LiveTradeHistory';
import { LiveTradePanel } from './ui/LiveTradePanel';
import { MarketControls } from './ui/MarketControls';
import { NoticeList } from './ui/NoticeList';

interface Props {
  market: LiveMarket;
  mode: Mode;
  onMode: (mode: Mode) => void;
}

/** The live market (rules.md §13): ten stocks that tick, candles of 10 ticks, instant trades. */
export function LiveApp({ market, mode, onMode }: Props) {
  const { view, controller, playing, speed, canStep } = market;
  // Which stock the chart and order panel show. Plain UI state — the engine does not care.
  const [selectedTicker, setSelectedTicker] = useState('QLRX');
  const stock = view.stocks.find((s) => s.ticker === selectedTicker) ?? view.stocks[0];

  const confirmLoss = (action: () => void, what: string) => () => {
    if (view.trades.length > 0 && !window.confirm(`${what}? Your trades in this session will be lost.`)) return;
    action();
  };

  return (
    <div className="app">
      <Header mode={mode} onMode={onMode}>
        <button type="button" className="btn btn-ghost" onClick={confirmLoss(() => controller.reset(), 'Restart this practice market from the beginning')}>
          Restart practice
        </button>
        <button type="button" className="btn btn-ghost" onClick={confirmLoss(() => controller.newSession(randomSeed()), 'Start a new practice market')}>
          New practice market
        </button>
      </Header>
      {stock && (
        <main className="layout">
          <div className="market-area">
            <LiveStockList stocks={view.stocks} selected={stock.ticker} onSelect={setSelectedTicker} />
          </div>
          <section className="card chart-card" aria-label={`${stock.ticker} live chart`}>
            <MarketControls
              view={view}
              playing={playing}
              speed={speed}
              canStep={canStep}
              onPlay={() => controller.play()}
              onPause={() => controller.pause()}
              onStep={() => controller.step()}
              onSkip={() => controller.skip()}
              onSpeed={(s) => controller.setSpeed(s)}
            />
            <LiveChart
              ticker={stock.ticker}
              name={stock.name}
              candles={stock.candles}
              price={stock.price}
              ticksPerCandle={view.ticksPerCandle}
              trades={view.trades.filter((t) => t.ticker === stock.ticker)}
              penKey={`practice:${view.seed}:${stock.ticker}`}
              penPersist={false}
            />
          </section>
          <section className="card holdings-card" aria-label="Your holdings">
            <h2>Your holdings</h2>
            <LiveHoldings stocks={view.stocks} selected={stock.ticker} onSelect={setSelectedTicker} />
          </section>
          <aside className="side">
            <LiveTradePanel key={stock.ticker} view={view} stock={stock} onOrder={(t, side, q) => controller.order(t, side, q)} />
            <NoticeList notices={view.notices} emptyText="Press Play to start the market, or Step to move it one tick at a time." />
            <LiveAccountPanel account={view.account} />
          </aside>
          <section className="card history-card" aria-label="Trade history">
            <h2>Trade history</h2>
            <LiveTradeHistory trades={view.trades} />
          </section>
        </main>
      )}
      <footer className="footer">
        Simulated market for education only. All ten companies and tickers are fictional; prices are generated by the
        TradeQuest engine (live market v{view.engineVersion}) and are not real market data. Practice mode runs only in this browser;
        the permanent shared market is the first tab. Seed {view.seed}. Start cash{' '}
        {formatCents(view.account.startCash)}.
      </footer>
    </div>
  );
}
