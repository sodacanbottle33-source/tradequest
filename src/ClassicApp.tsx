import { useState } from 'react';
import type { MarketControls } from './app/useMarket';
import { AccountPanel } from './ui/AccountPanel';
import { CandleChart } from './ui/CandleChart';
import { Header, type Mode } from './ui/Header';
import { HoldingsTable } from './ui/HoldingsTable';
import { NoticeList } from './ui/NoticeList';
import { OrderPanel } from './ui/OrderPanel';
import { ResultsScreen } from './ui/ResultsScreen';
import { StockList } from './ui/StockList';
import { TradeHistory } from './ui/TradeHistory';

interface Props {
  market: MarketControls;
  mode: Mode;
  onMode: (mode: Mode) => void;
}

/** The turn-based "Classic rounds" mode (rules.md §12): press Next candle, orders fill at the next open. */
export function ClassicApp({ market, mode, onMode }: Props) {
  const { view, results } = market;
  // Which stock the chart and order panel show. Plain UI state — the engine does not care.
  const [selectedTicker, setSelectedTicker] = useState('QLRX');
  const stock = view.stocks.find((s) => s.ticker === selectedTicker) ?? view.stocks[0];

  const confirmReset = (action: () => void, what: string) => () => {
    if (view.status === 'PLAYING' && !window.confirm(`${what}? Your current round will be lost.`)) return;
    action();
  };

  return (
    <div className="app">
      <Header mode={mode} onMode={onMode}>
        <button type="button" className="btn btn-ghost" onClick={confirmReset(market.replay, 'Replay this round from the start')}>
          Replay this round
        </button>
        <button type="button" className="btn btn-ghost" onClick={confirmReset(market.newRound, 'Start a new round')}>
          New round
        </button>
      </Header>
      {results ? (
        <ResultsScreen
          view={view}
          results={results}
          selected={stock ? stock.ticker : selectedTicker}
          onSelect={setSelectedTicker}
          onNewRound={market.newRound}
          onReplay={market.replay}
        />
      ) : (
        stock && (
          <main className="layout">
            <div className="market-area">
              <StockList stocks={view.stocks} selected={stock.ticker} onSelect={setSelectedTicker} />
            </div>
            <section className="card chart-card" aria-label={`${stock.ticker} price chart`}>
              <CandleChart
                candles={stock.candles}
                markPrice={stock.markPrice}
                roundNumber={view.roundNumber}
                roundLength={view.roundLength}
                ticker={stock.ticker}
                name={stock.name}
              />
            </section>
            <section className="card holdings-card" aria-label="Your holdings">
              <h2>Your holdings</h2>
              <HoldingsTable stocks={view.stocks} selected={stock.ticker} onSelect={setSelectedTicker} />
            </section>
            <aside className="side">
              <OrderPanel
                key={stock.ticker}
                view={view}
                stock={stock}
                onSubmit={market.submit}
                onCancel={market.cancel}
                onSelect={setSelectedTicker}
                onNext={market.next}
                onFinish={market.finish}
              />
              <NoticeList notices={view.notices} />
              <AccountPanel account={view.account} />
            </aside>
            <section className="card history-card" aria-label="Trade history">
              <h2>Trade history</h2>
              <TradeHistory trades={view.trades} />
            </section>
          </main>
        )
      )}
      <footer className="footer">
        Simulated market for education only. All ten companies and tickers are fictional; prices are generated by the
        TradeQuest engine (market v{view.engineVersion}) and are not real market data. Seed {view.seed}.
      </footer>
    </div>
  );
}
